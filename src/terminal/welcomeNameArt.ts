export interface WelcomeNameArt {
  label: string;
  glyphs: string[] | null;
}

/** Preserve the configured name; use plain text when compact art cannot fit it. */
export function buildWelcomeNameArt(name: string): WelcomeNameArt {
  const label = name.replace(/[\p{Cc}\p{Bidi_Control}\u2028\u2029]/gu, "").trim() || "HUSK";
  if (!/^[A-Za-z0-9 ]{1,12}$/.test(label)) return { label, glyphs: null };

  return {
    label,
    glyphs: [...label.toUpperCase()].map((character) => GLYPHS[character].join("\n")),
  };
}
